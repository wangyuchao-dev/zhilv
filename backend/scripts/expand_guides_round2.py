def insert(key: str, items: list) -> tuple[int, int]:
    path = os.path.join(DATA_DIR, f"{key}_guide.md")
    text = io.open(path, encoding="utf-8").read()

    # 用本次最后一条编号做幂等判断，重复跑不会插两遍
    last_no = items[-1][0]
    if f"### {last_no} " in text:
        return 0, len(text)

    blocks = [
        f"### {no} {name}\n位置：{loc}\n门票：{ticket}\n"
        f"游玩时长：{dur}\n简介：{desc}\n"
        for no, name, loc, ticket, dur, desc in items
    ]
    marker = "\n## 3."
    idx = text.find(marker)
    if idx == -1:
        raise RuntimeError(f"{path} 找不到「## 3.」章节")

    new_text = text[:idx] + "\n" + "\n".join(blocks) + text[idx:]
    io.open(path, "w", encoding="utf-8", newline="\n").write(new_text)
    return len(items), os.path.getsize(path)


