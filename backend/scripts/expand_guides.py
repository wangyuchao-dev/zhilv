def insert_additions(key: str, items: list) -> tuple[int, int]:
    path = os.path.join(DATA_DIR, f"{key}_guide.md")
    text = io.open(path, encoding="utf-8").read()

    # 已经补过就跳过，避免重复插入
    if f"### {items[0][0]} " in text:
        return 0, len(text)

    blocks = []
    for no, name, loc, ticket, dur, desc in items:
        blocks.append(
            f"### {no} {name}\n"
            f"位置：{loc}\n"
            f"门票：{ticket}\n"
            f"游玩时长：{dur}\n"
            f"简介：{desc}\n"
        )
    block = "\n".join(blocks)

    marker = "\n## 3."
    idx = text.find(marker)
    if idx == -1:
        raise RuntimeError(f"{path} 里找不到「## 3.」章节，格式可能变了")

    new_text = text[:idx] + "\n" + block + text[idx:]
    io.open(path, "w", encoding="utf-8", newline="\n").write(new_text)
    return len(items), len(new_text)


