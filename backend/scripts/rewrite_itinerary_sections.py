def build_text(items: list) -> str:
    out = [HEAD]
    for no, name, include, dur, arrive, fit, link in items:
        out.append(f"""### {no} {name}
包含：{include}
建议时长：{dur}
到达：{arrive}
适合：{fit}
衔接提示：{link}
""")
    return "\n".join(out)


def rewrite(key: str, items: list) -> tuple[bool, int]:
    path = os.path.join(DATA_DIR, f"{key}_guide.md")
    text = io.open(path, encoding="utf-8").read()

    # 匹配整个 ## 5 章节，直到 ## 6 或文件末尾
    pattern = re.compile(r"\n## 5\..*?(?=\n## 6\.|\Z)", re.S)
    if not pattern.search(text):
        raise RuntimeError(f"{path} 找不到 ## 5 章节")

    new_text = pattern.sub("\n" + build_text(items).rstrip() + "\n", text, count=1)
    io.open(path, "w", encoding="utf-8", newline="\n").write(new_text)
    return True, os.path.getsize(path)


